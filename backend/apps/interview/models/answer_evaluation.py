"""
ThreadEvaluation: LLM evaluation of a full topic thread (all turns
between the AI asking a seed topic and moving to the next one).

Why thread-level, not turn-level
---------------------------------
A single candidate turn tells you almost nothing. What matters is how
they perform *under pressure across a full exchange*:

  AI:        "Walk me through a tricky migration..."
  Candidate: "We used a three-phase approach..."    ← looks great in isolation
  AI:        "What about in-flight writes during backfill?"
  Candidate: "Uh... we just made sure it was fast" ← thread exposes the gap

ThreadEvaluation is created when the AI calls ask_next_question,
meaning the topic is complete and the full thread is available.

InterviewBrief is created once after the full interview ends,
aggregating all ThreadEvaluations into a human-readable brief with
suggested follow-up questions for the next round.
"""
import uuid

from django.conf import settings
from django.db import models


class ThreadEvaluation(models.Model):
    """Evaluation of one complete topic thread."""

    class Verdict(models.TextChoices):
        STRONG = "strong", "Strong"
        SURFACE = "surface", "Surface-level"
        BLUFFING = "bluffing", "Possible bluffing"
        WEAK = "weak", "Weak"
        INSUFFICIENT = "insufficient", "Insufficient data"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    interview = models.ForeignKey(
        "interview.InterviewSession",
        on_delete=models.CASCADE,
        related_name="thread_evaluations",
    )

    # The seed topic this thread was exploring.
    seed_topic = models.OneToOneField(
        "interview.Question",
        on_delete=models.CASCADE,
        related_name="thread_evaluation",
    )

    # --- What Gemini can actually observe ---

    # Did answers get deeper or shallower under follow-up probing?
    depth_under_pressure = models.FloatField(
        null=True, blank=True,
        help_text="Did the candidate go deeper when probed? (0–10)",
    )
    # Did they use terminology correctly in context, not just name-drop?
    conceptual_accuracy = models.FloatField(
        null=True, blank=True,
        help_text="Correct use of concepts in context, not just buzzwords. (0–10)",
    )
    # Concrete details (numbers, failure modes, tradeoffs) vs vague claims.
    specificity = models.FloatField(
        null=True, blank=True,
        help_text="Concrete details vs generic statements. (0–10)",
    )
    # When probed on something wrong or vague, did they recover?
    recovery = models.FloatField(
        null=True, blank=True,
        help_text="Handled being wrong or vague gracefully. (0–10)",
    )

    # Weighted overall for this thread.
    overall_score = models.FloatField(null=True, blank=True)

    # --- Qualitative outputs (more useful than scores) ---

    verdict = models.CharField(
        max_length=14,
        choices=Verdict.choices,
        default=Verdict.INSUFFICIENT,
    )

    # Specific quotes/observations from the conversation.
    red_flags = models.JSONField(
        default=list,
        help_text="Quotes or patterns suggesting surface-level knowledge.",
    )
    strong_signals = models.JSONField(
        default=list,
        help_text="Quotes or patterns suggesting genuine experience.",
    )

    # Generated by Gemini — targeted questions for the next human round
    # to follow up on weaknesses or contradictions found in this thread.
    suggested_followups = models.JSONField(
        default=list,
        help_text="Specific follow-up questions for the next interview round.",
    )

    # True when the verdict warrants a human listening to this thread
    # before advancing the candidate.
    requires_human_review = models.BooleanField(default=False)
    human_review_reason = models.TextField(blank=True)

    # Number of turns in the thread (for analytics).
    turn_count = models.PositiveSmallIntegerField(default=0)
    candidate_turn_count = models.PositiveSmallIntegerField(default=0)

    model_used = models.CharField(max_length=80, blank=True, default="")
    raw_response = models.JSONField(default=dict, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        app_label = "interview"
        db_table = "interview_thread_evaluations"
        ordering = ["seed_topic__order"]
        indexes = [models.Index(fields=["interview"])]

    def __str__(self) -> str:
        return f"ThreadEvaluation(interview={self.interview_id}, topic={self.seed_topic_id}, verdict={self.verdict})"  # type: ignore[attr-defined]


class InterviewBrief(models.Model):
    """
    Post-interview brief for the human making the hire decision.

    Aggregated from all ThreadEvaluations after the call ends.
    This is what a recruiter or hiring manager reads — not a score,
    but a structured brief that makes the next human touchpoint sharper.
    """

    class OverallSignal(models.TextChoices):
        STRONG = "strong", "Strong across topics"
        MIXED = "mixed", "Mixed — strong on some, weak on others"
        SURFACE = "surface", "Surface-level throughout"
        INCONSISTENT = "inconsistent", "Inconsistent — possible bluffing on some topics"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    interview = models.OneToOneField(
        "interview.InterviewSession",
        on_delete=models.CASCADE,
        related_name="brief",
    )

    overall_signal = models.CharField(
        max_length=14,
        choices=OverallSignal.choices,
        null=True,
        blank=True,
    )

    # Narrative summary Gemini writes after seeing all thread results.
    summary = models.TextField(blank=True)

    # Cross-topic patterns Gemini detected.
    performs_under_pressure = models.BooleanField(
        null=True,
        help_text="True if answers consistently deepened under follow-up probing.",
    )
    specificity_consistent = models.BooleanField(
        null=True,
        help_text="True if candidate gave concrete details consistently across topics.",
    )
    self_contradictions_detected = models.BooleanField(
        default=False,
        help_text="True if the candidate contradicted themselves across topics.",
    )
    contradiction_detail = models.TextField(
        blank=True,
        help_text="Description of what was contradicted and where.",
    )

    # Aggregated across all threads.
    red_flags = models.JSONField(default=list)
    strong_signals = models.JSONField(default=list)

    # The most valuable output — targeted questions for the next round.
    suggested_followup_questions = models.JSONField(
        default=list,
        help_text="Specific questions for the next human interview round.",
    )

    requires_human_review = models.BooleanField(default=False)

    # Human fills these after reading the brief.
    human_verdict = models.CharField(
        max_length=10,
        choices=[("advance", "Advance"), ("reject", "Reject"), ("hold", "Hold")],
        null=True,
        blank=True,
    )
    human_notes = models.TextField(blank=True)
    reviewed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="reviewed_briefs",
    )
    reviewed_at = models.DateTimeField(null=True, blank=True)

    model_used = models.CharField(max_length=80, blank=True, default="")
    raw_response = models.JSONField(default=dict, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        app_label = "interview"
        db_table = "interview_briefs"

    def __str__(self) -> str:
        return f"InterviewBrief(interview={self.interview_id}, signal={self.overall_signal})"  # type: ignore[attr-defined]